// Local times for each ceremony of a sample: an evening before, the main event, an evening after.
function slots(count: number, date: string, tz: string): { start: string; end: string }[] {
  const day = (offset: number) => {
    const d = new Date(`${date}T12:00:00Z`);
    d.setUTCDate(d.getUTCDate() + offset);
    return d.toISOString().slice(0, 10);
  };
  const plan: [number, string, string][] =
    count === 1
      ? [[0, "11:00", "14:00"]]
      : count === 2
        ? [[0, "11:00", "13:00"], [0, "19:00", "22:00"]]
        : [[-1, "16:00", "20:00"], [0, "10:30", "13:00"], [0, "19:00", "23:00"]];
  return Array.from({ length: count }, (_, i) => {
    const [off, a, b] = plan[Math.min(i, plan.length - 1)];
    return { start: fromLocalInput(`${day(off)}T${a}`, tz), end: fromLocalInput(`${day(off)}T${b}`, tz) };
  });
}

// The design of a template applied on top of a fresh config. Used both for the live sample
// and for a real invitation the host starts from this template.
function applyDesign(t: Template, cfg: InviteConfig): InviteConfig {
  const p = PRESETS[t.preset];
  cfg.theme = { preset: t.preset, colors: { ...p.colors }, fonts: p.fonts, fireflies: p.fireflies, frame: t.frame, ornament: t.ornament, background: t.background ?? "flat", dateStyle: t.dateStyle ?? "stacked", titleStyle: t.titleStyle ?? "default", scene: t.scene ?? "none", photo: t.photo ?? "none", watercolor: t.watercolor ?? "none", bigAmpersand: t.bigAmpersand ?? false, layout: t.layout ?? "invitation" };
  cfg.texts.crest = t.crest;
  return cfg;
}

// A real starting point: the template's design and wording, the host's own names, no sample details.
export function starterFromTemplate(t: Template, name1: string, name2: string): InviteConfig {
  const cfg = applyDesign(t, defaultConfig(t.type, name1, name2, { tradition: t.tradition || undefined, language: t.language, timezone: t.timezone }));
  if (t.headline) cfg.event.headline = t.headline;
  if (t.eyebrow) cfg.texts.eyebrow = t.eyebrow;
  if (t.scheduleTitles?.length) cfg.schedule = t.scheduleTitles.map((title, i) => ({ key: `c${i}`, title, start: "", end: "", place: "", dress: "", note: "" }));
  return cfg;
}

