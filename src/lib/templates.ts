// Which visual style a template has, for the gallery's style filter.
export const STYLES = ["Watercolour", "Animated sky", "Photo", "Website", "Floral and garden", "Classic"] as const;
export function styleOf(t: Template): (typeof STYLES)[number] {
  if (t.layout === "website") return "Website";
  if (t.watercolor && t.watercolor !== "none") return "Watercolour";
  if (t.scene && t.scene !== "none") return "Animated sky";
  if (t.photo && t.photo !== "none") return "Photo";
  if (["garden", "wildflower", "floral", "leaves", "garland"].includes(t.ornament)) return "Floral and garden";
  return "Classic";
}
